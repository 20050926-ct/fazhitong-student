function normalizeQuestion(text: string): string {
  return text.toLowerCase().replace(/[，。！？、,.!?\s]/g, '');
}

export function getAiChatFixedAnswer(question: string): string {
  const trimmed = question.trim();
  const exactQuick = AI_CHAT_QUICK_ANSWERS[trimmed];
  if (exactQuick) return exactQuick;

  const typed = AI_CHAT_TYPED_FIXED_ANSWERS[trimmed];
  if (typed) return typed;

  const normalized = normalizeQuestion(trimmed);
  for (const rule of AI_CHAT_KEYWORD_RULES) {
    const hitCount = rule.keywords.filter((k) => normalized.includes(normalizeQuestion(k))).length;
    if (hitCount >= 2 || (rule.keywords.length === 1 && hitCount === 1)) {
      return rule.answer;
    }
  }
  return AI_CHAT_FALLBACK;
}

